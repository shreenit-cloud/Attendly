begin;

create table public.organizations (
  organization_id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  created_at timestamptz not null default now()
);

insert into public.organizations (name, slug)
values ('AI Attendance', 'ai-attendance')
on conflict (slug) do nothing;

alter table public.teachers add column organization_id bigint;
alter table public.teachers add column is_org_admin boolean not null default false;
alter table public.students add column organization_id bigint;
alter table public.classes add column organization_id bigint;
alter table public.attendance_sessions add column organization_id bigint;

update public.teachers set organization_id = (select organization_id from public.organizations where slug = 'ai-attendance');
update public.students set organization_id = (select organization_id from public.organizations where slug = 'ai-attendance');
update public.classes set organization_id = (select organization_id from public.organizations where slug = 'ai-attendance');
update public.attendance_sessions set organization_id = (select organization_id from public.organizations where slug = 'ai-attendance');
update public.teachers set is_org_admin = true where teacher_id = 2;

do $$ begin
  if not exists (select 1 from public.teachers where teacher_id = 2) then
    raise exception 'Expected initial organization admin teacher_id=2 was not found';
  end if;
end $$;

alter table public.teachers alter column organization_id set not null;
alter table public.students alter column organization_id set not null;
alter table public.classes alter column organization_id set not null;
alter table public.attendance_sessions alter column organization_id set not null;

alter table public.teachers add constraint teachers_organization_id_fkey foreign key (organization_id) references public.organizations(organization_id) on delete cascade;
alter table public.students add constraint students_organization_id_fkey foreign key (organization_id) references public.organizations(organization_id) on delete cascade;
alter table public.classes add constraint classes_organization_id_fkey foreign key (organization_id) references public.organizations(organization_id) on delete cascade;
alter table public.attendance_sessions add constraint sessions_organization_id_fkey foreign key (organization_id) references public.organizations(organization_id) on delete cascade;

create table public.organization_invites (
  invite_id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations(organization_id) on delete cascade,
  role text not null check (role in ('teacher', 'student')),
  code_hash text not null unique,
  expires_at timestamptz not null,
  claimed_by text,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

create index teachers_organization_id_idx on public.teachers(organization_id);
create index students_organization_id_idx on public.students(organization_id);
create index classes_organization_id_idx on public.classes(organization_id);
create index sessions_organization_id_idx on public.attendance_sessions(organization_id);

-- All API traffic currently uses the backend service-role key; enforce tenant scope in backend authorization.
-- RLS remains enabled, but policies for a custom JWT would not be valid Supabase auth.uid() policies.
commit;
