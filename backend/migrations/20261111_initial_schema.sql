-- Initial schema for a fresh AI Attendance Supabase project.

begin;

create table public.teachers (
  teacher_id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table public.students (
  student_id bigint generated by default as identity primary key,
  prn text not null unique check (prn ~ '^[0-9]{10}$'),
  name text not null,
  password_hash text not null,
  face_embedding jsonb,
  created_at timestamptz not null default now()
);

create table public.classes (
  class_id bigint generated by default as identity primary key,
  teacher_id bigint not null references public.teachers(teacher_id) on delete cascade,
  name text not null,
  code text not null,
  schedule_description text,
  created_at timestamptz not null default now()
);

create table public.class_enrollments (
  enrollment_id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(class_id) on delete cascade,
  student_id bigint not null references public.students(student_id) on delete cascade,
  enrolled_at timestamptz not null default now(),
  unique (class_id, student_id)
);

create table public.attendance_sessions (
  session_id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(class_id) on delete cascade,
  teacher_id bigint not null references public.teachers(teacher_id) on delete cascade,
  room_number text,
  status text not null default 'active' check (status in ('active', 'closed')),
  started_at timestamptz not null default now(),
  closed_at timestamptz
);

create table public.attendance_records (
  record_id bigint generated by default as identity primary key,
  session_id bigint not null references public.attendance_sessions(session_id) on delete cascade,
  student_id bigint not null references public.students(student_id) on delete cascade,
  status text not null default 'present' check (status in ('present', 'absent', 'late')),
  confidence_score real,
  method text not null default 'face_recognition',
  notes text,
  marked_at timestamptz not null default now(),
  unique (session_id, student_id)
);

create index classes_teacher_id_idx on public.classes(teacher_id);
create index class_enrollments_student_id_idx on public.class_enrollments(student_id);
create index attendance_sessions_class_id_idx on public.attendance_sessions(class_id);
create index attendance_sessions_teacher_id_idx on public.attendance_sessions(teacher_id);
create index attendance_records_student_id_idx on public.attendance_records(student_id);
create index attendance_records_session_id_idx on public.attendance_records(session_id);

alter table public.teachers enable row level security;
alter table public.students enable row level security;
alter table public.classes enable row level security;
alter table public.class_enrollments enable row level security;
alter table public.attendance_sessions enable row level security;
alter table public.attendance_records enable row level security;

commit;
